#!/usr/bin/env node
import { writeFile } from 'node:fs/promises';
import sharp from 'sharp';
import { CANVAS, buildGlobalLand, countRings, projectGlobeLand } from './lib/atlas-globe.mjs';
import { fetchPinnedSource } from './lib/pinned-natural-earth.mjs';

const ICONS_DIR = new URL('../public/icons/', import.meta.url);

/**
 * The locked Atlas globe. Every published asset derives from this one object,
 * so the SVG and every raster stay the same mark.
 *
 * `centre` was selected by comparing Africa-centred candidates A (15, 10),
 * B (15, 15) and C (20, 12) at 1024, 512, 192, 64, 32 and 24 px against an
 * unsimplified projection of the same source. A keeps Africa centred with
 * margin from the limb while retaining Madagascar, the Horn, the Gulf of
 * Guinea, the Mediterranean, Iberia/Italy and Arabia.
 */
export const ATLAS_GLOBE = {
  centre: [15, 10],
  canvas: CANVAS,
  widthRatio: 0.74,
  // topojson-simplify retains this fraction of source points; smaller is coarser.
  retainedPointFraction: 0.05,
  // Projected-space thresholds, in canvas units, applied after projection.
  minimumStep: 2.5,
  minimumRingArea: 8,
  digits: 1,
  cornerRadius: 224,
  background: '#101318',
  land: '#ffffff',
};

const PROVENANCE = (url) => `<!-- Generated by scripts/generate-brand-icons.mjs. Do not hand-edit.
     Source: pinned Natural Earth Admin-0 countries, ${url}
     Projection: geoOrthographic, centre ${ATLAS_GLOBE.centre.join(', ')}, globe width ${ATLAS_GLOBE.widthRatio} of canvas. -->`;

function markSvg(path, url) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS} ${CANVAS}" width="${CANVAS}" height="${CANVAS}" role="img" aria-label="Atlas">
${PROVENANCE(url)}
  <path d="${path}" fill="${ATLAS_GLOBE.land}"/>
</svg>
`;
}

function appIconSvg(path, url, { maskable }) {
  const field = maskable
    ? `<rect width="${CANVAS}" height="${CANVAS}" fill="${ATLAS_GLOBE.background}"/>`
    : `<rect width="${CANVAS}" height="${CANVAS}" rx="${ATLAS_GLOBE.cornerRadius}" ry="${ATLAS_GLOBE.cornerRadius}" fill="${ATLAS_GLOBE.background}"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS} ${CANVAS}" width="${CANVAS}" height="${CANVAS}" role="img" aria-label="Atlas">
${PROVENANCE(url)}
  ${field}
  <path d="${path}" fill="${ATLAS_GLOBE.land}"/>
</svg>
`;
}

async function writeSvg(name, contents) {
  await writeFile(new URL(name, ICONS_DIR), contents);
  return contents;
}

async function writePng(name, svg, size) {
  const buffer = await sharp(Buffer.from(svg), { density: 384 })
    .resize(size, size)
    .png({ compressionLevel: 9 })
    .toBuffer();
  await writeFile(new URL(name, ICONS_DIR), buffer);
}

const source = await fetchPinnedSource('countries');
const land = buildGlobalLand(source.json(), ATLAS_GLOBE.retainedPointFraction);
const path = projectGlobeLand(land, ATLAS_GLOBE);
if (!path) throw new Error('Atlas globe projection produced no geometry.');

const regular = appIconSvg(path, source.url, { maskable: false });
const maskable = appIconSvg(path, source.url, { maskable: true });

await writeSvg('atlas-globe.svg', markSvg(path, source.url));
await writeSvg('app-icon.svg', regular);
await writeSvg('app-icon-maskable.svg', maskable);
await writePng('app-icon-192.png', regular, 192);
await writePng('app-icon-512.png', regular, 512);
await writePng('app-icon-1024.png', regular, 1024);
await writePng('app-icon-maskable-512.png', maskable, 512);
await writePng('apple-touch-icon.png', maskable, 180);

console.log(
  `Generated the Atlas globe mark from ${source.url}: `
  + `${countRings(path)} land rings, centre ${ATLAS_GLOBE.centre.join(', ')}.`,
);
